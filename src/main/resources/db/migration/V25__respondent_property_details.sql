CREATE TABLE respondent_property_details (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  respond_to_tenant_answers_about_tenancy_details YES_NO,
  respond_to_tenant_answers_about_tenancy_details_description VARCHAR (500),
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_modified_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_modified_by VARCHAR (100),
  market_rent_case_id BIGINT NOT NULL UNIQUE REFERENCES market_rent_case (id)
);

CREATE INDEX respondent_property_details_market_rent_case_id_idx
  ON respondent_property_details (market_rent_case_id);
